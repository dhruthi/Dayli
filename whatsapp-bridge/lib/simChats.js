/**
 * Returns the 15 simulated scenarios enriched with nearest ready labour room
 * metadata and classified service category badges.
 */
export function getSimulatedWomenObservatory() {
  return SIMULATED_WOMEN_SCENARIOS.map((item) => {
    const { nearest, backup } = findNearestReadyLabourRoom(item.lat, item.lon);
    const firstQuery = item.turns.find((t) => t.role === 'user')?.text || '';
    const svc = classifyChatServiceCategory(firstQuery, item.subjectType);

    return {
      ...item,
      simulated: true,
      serviceId: svc.id,
      serviceLabel: svc.label,
      serviceIcon: svc.icon,
      serviceBadgeClass: svc.badgeClass,
      nearestHospital: nearest
        ? {
            id: nearest.id,
            shortName: nearest.shortName,
            distanceKm: nearest.distanceKm,
            etaMinutes: nearest.etaMinutes,
            readyLabourRooms: nearest.readyLabourRooms,
            nicuBedsAvailable: nearest.nicuBedsAvailable,
            emergencyPhone: nearest.emergencyPhone,
            backupShortName: backup?.shortName || null,
          }
        : null,
    };
  });
}
